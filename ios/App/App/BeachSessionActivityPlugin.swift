    // MARK: - DEBUG probe (verifies the code path without the WebView)
    //
    // Exercised by AppDelegate when launched with
    // `--probe-live-activity-plugin` — calls start/update/end through the
    // SAME static parse/encode helpers and Activity<> calls the bridge uses,
    // proving the plugin class is registered and this code path runs, without
    // needing a live WKWebView round-trip (which xcrun simctl can't drive).
    #if DEBUG
    static func runProbe() {
        #if canImport(ActivityKit)
        if #available(iOS 16.2, *) {
            guard ActivityAuthorizationInfo().areActivitiesEnabled else {
                print("[LiveActivityProbe] skipped: Live Activities not enabled")
                return
            }
            let nowMs = Date().timeIntervalSince1970 * 1000
            let attrsObj: [String: Any] = ["beachName": "Probe Beach", "slug": "probe-beach", "sessionStart": nowMs]
            let stateObj: [String: Any] = ["v": 1, "seq": 0, "score": 77, "updatedAt": nowMs]
            guard let attributes = parseAttributes(attrsObj), let content = parseContentState(stateObj) else {
                print("[LiveActivityProbe] FAILED: parse rejected known-good probe payloads")
                return
            }

            // Codable round-trip check: ActivityKit serializes ContentState
            // between the app and the widget extension (and on every local
            // update) through Codable, not just for an APNs push decode. A
            // mismatched encode(to:)/init(from:) pair would silently corrupt
            // every date field reaching the Lock Screen. Independent of the
            // Activity<> calls below, so it always runs.
            do {
                let sample = BeachSessionAttributes.ContentState(
                    v: 1, seq: 2, score: 50,
                    nextTideAt: Date(timeIntervalSince1970: 1_800_000_000.123),
                    sunsetAt: Date(timeIntervalSince1970: 1_800_050_000.456),
                    lightning: BeachSessionAttributes.ContentState.Lightning(
                        active: true, latched: false,
                        observedAt: Date(timeIntervalSince1970: 1_800_010_000.789),
                        holdUntil: Date(timeIntervalSince1970: 1_800_020_000.321)
                    ),
                    updatedAt: Date(timeIntervalSince1970: 1_800_030_000.654)
                )
                let data = try JSONEncoder().encode(sample)
                let decoded = try JSONDecoder().decode(BeachSessionAttributes.ContentState.self, from: data)
                let pairs: [(String, Date?, Date?)] = [
                    ("updatedAt", sample.updatedAt, decoded.updatedAt),
                    ("nextTideAt", sample.nextTideAt, decoded.nextTideAt),
                    ("sunsetAt", sample.sunsetAt, decoded.sunsetAt),
                    ("lightning.observedAt", sample.lightning?.observedAt, decoded.lightning?.observedAt),
                    ("lightning.holdUntil", sample.lightning?.holdUntil, decoded.lightning?.holdUntil),
                ]
                var allOK = true
                for (name, a, b) in pairs {
                    guard let a, let b else {
                        if (a != nil) != (b != nil) {
                            allOK = false
                            print("[LiveActivityProbe] round-trip FAILED: \(name) nil mismatch")
                        }
                        continue
                    }
                    let diffMs = abs(a.timeIntervalSince(b)) * 1000
                    if diffMs > 1 {
                        allOK = false
                        print("[LiveActivityProbe] round-trip FAILED: \(name) off by \(diffMs)ms")
                    }
                }
                print(allOK
                    ? "[LiveActivityProbe] round-trip OK — Codable dates preserved"
                    : "[LiveActivityProbe] round-trip FAILED — see above")
            } catch {
                print("[LiveActivityProbe] round-trip FAILED: \(error)")
            }

            Task {
                for existing in Activity<BeachSessionAttributes>.activities {
                    cancelObservers(for: existing.id)
                    await existing.end(existing.content, dismissalPolicy: .immediate)
                }
                do {
                    let activityContent = ActivityContent(state: content.state, staleDate: nil)
                    // pushType stays nil here, same as before Phase 3: a
                    // push-token activity needs the aps-environment
                    // entitlement actually applied, which an unsigned/ad-hoc
                    // probe build doesn't have, and that's not what this
                    // probe is for. The Phase 3 upload path is exercised
                    // directly below instead, with a dummy deviceId and a
                    // synthetic hex token standing in for a real rotation —
                    // the register/end POSTs it fires may 4xx or simply time
                    // out against a simulator with no reachable network
                    // route, and that must stay silent (postJSON never
                    // throws or blocks); it is not treated as a probe
                    // failure.
                    let activity = try Activity.request(attributes: attributes, content: activityContent, pushType: nil)
                    // Dummy install token — the /register and /end uploads
                    // below may 4xx (server doesn't know this token) or time
                    // out against a simulator with no reachable network
                    // route, and that must stay silent per postJSON's own
                    // 4xx/no-retry rule; it is not a probe failure.
                    let meta = ActivityMeta(deviceId: "probe-device-000000000000", appBuild: nil, slug: activity.attributes.slug, installToken: "probe-install-token-0000000000", rotation: 0)
                    activityMeta[activity.id] = meta
                    keychainSave(id: activity.id, meta: meta)
                    print("[LiveActivityProbe] start OK activityId=\(activity.id)")
                    uploadPushToken(activityId: activity.id, token: "00" + String(repeating: "ab", count: 31))
                    let updated = BeachSessionAttributes.ContentState(
                        v: 1, seq: 1, score: 80, updatedAt: Date()
                    )
                    await activity.update(ActivityContent(state: updated, staleDate: nil))
                    print("[LiveActivityProbe] update OK")
                    uploadEnd(activityId: activity.id)
                    await activity.end(ActivityContent(state: updated, staleDate: nil), dismissalPolicy: .immediate)
                    cancelObservers(for: activity.id) // clears memory + Keychain now that it's confirmed ended
                    print("[LiveActivityProbe] end OK — plugin code path verified")
                } catch {
                    print("[LiveActivityProbe] start FAILED: \(error)")
                }
            }
            return
        }
        #endif
        print("[LiveActivityProbe] skipped: iOS < 16.2 or ActivityKit unavailable")
    }

