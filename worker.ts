// The Worker entry (wrangler.jsonc "main"). It wraps OpenNext's generated worker so the agent
// paths (/mcp, /api/v1/*, /api/watch/*, /llms.txt) are sent as complete bodies with a
// Content-Length instead of a chunked stream; see lib/workerWrap.ts. Every named export of the
// generated worker (the Durable Object classes OpenNext declares) is re-exported unchanged,
// and every other path goes straight through, so streaming pages keep streaming. Around that,
// the edge cache (lib/edgeCache.ts) serves the beach pages and the conditions JSON.
//
// `.open-next/worker.js` exists only after `opennextjs-cloudflare build`, so tsconfig.json
// excludes this file from type checking and the imports below carry no types.

