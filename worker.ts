import openNext from "./.open-next/worker.js";
import { withBufferedAgentResponses } from "./lib/workerWrap";
import { withEdgeCache } from "./lib/edgeCache";

// @ts-ignore generated by `opennextjs-cloudflare build`
export * from "./.open-next/worker.js";

// Outermost: the edge cache (lib/edgeCache.ts) answers repeat requests for the beach pages and
// /api/conditions/<slug> from a stored copy. It never touches the buffered agent paths.
export default withEdgeCache(withBufferedAgentResponses(openNext));
